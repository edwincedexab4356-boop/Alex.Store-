export const resetToSeedData = () => {
  if (typeof window !== 'undefined') {
    localStorage.setItem('alexstore_products', JSON.stringify(INITIAL_PRODUCTS));
    localStorage.setItem('alexstore_categories', JSON.stringify(INITIAL_CATEGORIES));
    localStorage.setItem('alexstore_settings', JSON.stringify(INITIAL_SETTINGS));
    localStorage.removeItem('alexstore_orders');
    window.dispatchEvent(new CustomEvent('alexstore:change', { detail: { entity: 'all' } }));
  }
};
